const colors: Record<string, string> = { orange: "オレンジ", yellow: "黄色", green: "緑", blue: "青", purple: "紫", pink: "ピンク", red: "赤" };
const koreanColors: Record<string, string> = { orange: "주황", yellow: "노랑", green: "초록", blue: "파랑", purple: "보라", pink: "분홍", red: "빨강" };
export const cueColorLabel = (color: string, locale: InterfaceLocale) => locale === "ja" ? colors[color] || color : locale === "ko" ? koreanColors[color] || color : color;
export function translate(text: string, locale: InterfaceLocale): string {
  if (locale === "en") return text;
  const dictionary = locale === "ko" ? korean : japanese;
  if (dictionary[text]) return dictionary[text];
  if (dictionary[text.trim()]) return text.replace(text.trim(), dictionary[text.trim()]);
  const patterns: [RegExp, (...groups: string[]) => string][] = [
    [/^Audio unavailable\. Text clue \(hint\): (.+)$/, word => locale === "ko" ? `소리를 재생할 수 없어요. 글자 힌트: ${word}` : `音声を再生できません。文字のヒント：${word}`],
    [/^The answer was (.+)\. This counts as a missed question\.$/, word => locale === "ko" ? `정답은 ${word}예요. 이 문제는 오답으로 기록돼요.` : `正解は ${word} でした。この問題は不正解として記録されます。`],
    [/^Practice: (\d+)\/6 words recalled first-try in both activities$/, n => locale === "ko" ? `연습: 두 활동에서 첫 번째에 맞힌 단어 ${n}/6` : `練習：2種類の問題で最初に正解した英単語 ${n}/6`],
    [/^(Mixed check|Spaced review): (\d+)\/(\d+)$/, (kind,n,total) => locale === "ko" ? `${kind === "Mixed check" ? "확인 문제" : "간격을 둔 복습"}: ${n}/${total}` : `${kind === "Mixed check" ? "確認問題" : "日をあけた復習"}：${n}/${total}`],
    [/^Memory color for (.+)$/, word => locale === "ko" ? `${word} 기억 색깔` : `${word} の記憶カラー`],
    [/^Letter (.+), tile (\d+)$/, (letter,n) => locale === "ko" ? `영어 글자 ${letter}, 타일 ${n}` : `英字 ${letter}、タイル ${n}`],
    [/^(Sketch|Word): (.+)$/, (kind,word) => locale === "ko" ? `${kind === "Sketch" ? "그림" : "영어 단어"}: ${word}` : `${kind === "Sketch" ? "絵" : "英単語"}：${word}`],
    [/^Which (picture|word) did you pair with (.+)\?$/, (kind,color) => locale === "ko" ? `${koreanColors[color] || color} 색과 연결한 ${kind === "picture" ? "그림" : "단어"}는 무엇일까요?` : `${colors[color] || color}と組み合わせた${kind === "picture" ? "絵" : "英単語"}はどれ？`],
  ];
  for (const [pattern, format] of patterns) { const match = text.match(pattern); if (match) return format(...match.slice(1)); }
  return text;
}
// Pure render-time localization, not DOM mutation. Only host elements are walked;
// each game localizes its own subtree. Internal identifiers and event handlers stay intact.
export function localizeTree(node: ReactNode, locale: InterfaceLocale): ReactNode {
  if (typeof node === "string") return translate(node, locale);
  if (Array.isArray(node)) return Children.map(node, child => localizeTree(child, locale));
  if (!isValidElement(node) || (typeof node.type !== "string" && node.type !== Fragment)) return node;
  const element = node as ReactElement<Record<string, unknown>>;
  if (element.props.lang === "en") return node;
  const props: Record<string, unknown> = {};
  if (typeof element.props.children === "string" && /^(apple|banana|pear|grape|lemon|strawberry|[a-z])$/.test(element.props.children)) props.lang = "en";
  for (const attr of ["aria-label", "title"]) if (typeof element.props[attr] === "string") props[attr] = translate(element.props[attr] as string, locale);
  if (node.type === "option" && typeof element.props.children === "string" && colors[element.props.children]) {
    props.value = element.props.value ?? element.props.children;
    props.children = cueColorLabel(element.props.children, locale);
  } else if (element.props.children !== undefined) props.children = localizeTree(element.props.children as ReactNode, locale);
  return cloneElement(element, props);
}
